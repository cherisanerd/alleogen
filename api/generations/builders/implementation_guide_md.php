/**
 * @param array<string, mixed> $ctx
 * @return array{'Implementation_Guide.md': string}
 */
function build_implementation_guide_md(array $ctx): array
{
    $tier       = $ctx['package_tier'];
    $data       = $ctx['data'];
    $ex         = $ctx['ex'];
    $today      = $ctx['today'];
    $url        = $ctx['website_url'];
    $businessName = $ctx['businessNameFinal'];
    $email      = (string) ($data['contactEmail'] ?? 'support');

    $platformName = (string) ($data['platform'] ?? $ex['platform'] ?? 'Custom/Other');

    $platformSeoSteps = [
