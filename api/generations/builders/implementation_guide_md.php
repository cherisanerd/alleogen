            '3. Also in <head>, paste the meta-tags.html content.',
            '4. If you use a CDN, purge cache after upload.',
        ],
    ];
    $seoStepLines = implode("\n", $platformSeoSteps[$platformName] ?? $platformSeoSteps['Custom/Other']);

    $aeoExtra = $tier === 'complete'
        ? "- **llms.txt** and **llms-full.txt** also go at the site root: {$url}/llms.txt, {$url}/llms-full.txt.\n- **.well-known/ai.json** goes at {$url}/.well-known/ai.json."
        : '';

    $geoBlock = $tier === 'complete'
        ? "- Open `geo-content-brief.md`. Use the **Brand Positioning Statement** as canonical copy in your About page, hero section, and PR boilerplate.\n"
          . "- Publish the **Quotable Expert Answers** as a FAQ page on your site. AI systems preferentially cite FAQ-formatted content.\n"
