        '- **Annually:** review and reaffirm topic ownership (Q11) — topical authority compounds over time only if the topic set stays stable.',
        '',
        '## Support',
        '',
        "Questions? Contact: {$email}",
        '',
    ];

    return ['Implementation_Guide.md' => implode("\n", $lines)];
